b = int(input("первый элемент прогрессии="))
q = int(input("множитель прогрессии ="))
n = int(input("номер последнего элемента="))

summa = 0

for i in range (n): # запуск цикла
    summa +=b # прибавим элемент b к общей сумме
    b*=q # умножим элемент b на q и перейдём к следующему члену прогрессии
print("результат вычисления суммы геометрической прогрессии=", summa) # вывод суммы
