n = int(input("введите число= "))
a = 0 # введем счетчик

for i in range (2, n//2+1): # запуск цикла
    if (n%i==0):
        a=a+1 # если делится то переменная увеличивается на 1
if (a==0): # если число делителей равно 0
        print ("Y") # число простое
else:
    print("N") # число не простое
